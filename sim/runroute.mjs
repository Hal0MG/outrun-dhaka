// The Run's route as distances along it, for the HUD (src/world/runroute.js): where each district begins, where its
// gate is, and the finish. The game builds the districts' roads one at a time as you near them, so it cannot know the
// whole length up front; this builds them all (as sim/env.mjs does) and writes the numbers down.
//   node sim/runroute.mjs        rewrite src/world/runroute.js (run it again if a district's road changes)
import { writeFileSync } from 'node:fs';
import { RaceEnv } from './env.mjs';
import { ROUTE } from '../src/world/stages.js';

const env = new RaceEnv({ mode: 'run' });
env.reset({ seed: 1 });
// env.reset has built the chain; walk it by the route
const tracks = [];
let tr = env.track;
tracks.push(tr);
while (tr.children?.[0] && tr.children[0] !== tr) { tr = tr.children[0]; tracks.push(tr); if (tracks.length > ROUTE.length) break; }
if (tracks.length !== ROUTE.length) throw new Error(`expected ${ROUTE.length} districts, found ${tracks.length}`);
const start = {}, gate = {};
tracks.forEach((t, i) => { start[ROUTE[i]] = Math.round(t.base); gate[ROUTE[i]] = Math.round(t.base + t.gateS); });
const last = tracks[tracks.length - 1];
const out = `// Generated by sim/runroute.mjs: The Run as metres along the route, for the HUD. Do not edit by hand.
export const RUN_ROUTE = ${JSON.stringify({ start, gate, finish: Math.round(last.base + last.goalS) }, null, 2)};
`;
writeFileSync(new URL('../src/world/runroute.js', import.meta.url), out);
console.log(out);
